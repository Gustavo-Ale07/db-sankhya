/**
 * Functions a Sankhya read may call. Everything else (package functions,
 * user-defined functions, system procedures) is refused by the read analyzer.
 * Names are upper-case; matching is case-insensitive.
 */
export const ALLOWED_FUNCTIONS: ReadonlySet<string> = new Set([
  'COUNT',
  'SUM',
  'AVG',
  'MIN',
  'MAX',
  'COALESCE',
  'NVL',
  'ISNULL',
  'NULLIF',
  'UPPER',
  'LOWER',
  'TRIM',
  'LTRIM',
  'RTRIM',
  'SUBSTR',
  'SUBSTRING',
  'LENGTH',
  'LEN',
  'REPLACE',
  'CONCAT',
  'ROUND',
  'TRUNC',
  'FLOOR',
  'CEIL',
  'CEILING',
  'ABS',
  'MOD',
  'CAST',
  'CONVERT',
  'TO_CHAR',
  'TO_DATE',
  'TO_NUMBER',
  'SYSDATE',
  'GETDATE',
  'CURRENT_DATE',
  'CURRENT_TIMESTAMP',
  'EXTRACT',
  'DATEADD',
  'DATEDIFF',
  'ADD_MONTHS',
  'MONTHS_BETWEEN',
  'LPAD',
  'RPAD',
  'DECODE',
  'ROW_NUMBER',
  'RANK',
  'DENSE_RANK',
  'YEAR',
  'MONTH',
  'DAY',
]);

export function isAllowedFunction(name: string): boolean {
  return ALLOWED_FUNCTIONS.has(name.toUpperCase());
}
